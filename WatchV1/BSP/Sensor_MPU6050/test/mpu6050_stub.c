/* ============================================================================
 * mpu6050_stub.c —— MPU6050 的「测试替身」(stub)
 *
 * 作用：顶替 BSP/Sensor_MPU6050/mpu6050.c，让 mpu6050_handler 能在 PC 上被测。
 *       链接时「换掉同名符号」即可 —— mpu6050_handler.c 一个字都不用改。
 *
 * 三条要求（同 aht21_stub.c）：
 *   ① 头文件里声明的函数都要实现（少一个 → 链接器报 undefined symbol）
 *   ② 一行 I2C、一行 HAL 都不能有（它只跟变量打交道）
 *   ③ 测试能「指挥」它 —— 这是 stub 的灵魂
 * ==========================================================================*/

#include "mpu6050.h"
#include <stdint.h>

/* ---------------------------------------------------------------------------
 * 【遥控杆】—— 测试开跑前设定，stub 照着演
 *            桩自己【不含任何判断逻辑】，只负责把设定播出去
 * -------------------------------------------------------------------------*/

mpu6050_err_t   stub_init_err   = MPU6050_OK;   /* mpu6050_init 该返回什么       */
mpu6050_err_t   stub_read_err   = MPU6050_OK;   /* mpu6050_read 该报什么错       */
uint32_t        stub_fail_times = 0;            /* 那个错「还要再报几次」0 = 不报了 */

/* 成功时吐出的【一整包】—— 用一个 struct 变量，而不是一堆散装标量
 *   理由：真驱动的出参就是 mpu6050_data_t，桩照同一个形状演，测试才比得对 */
mpu6050_data_t  stub_data =
{
    .raw  = { .ax = 0, .ay = 0, .az = 16384, .temp = 1000,
              .gx = 0, .gy = 0, .gz = 0 },
    .conv = { .ax_g = 0.0f, .ay_g = 0.0f, .az_g = 1.0f, .temp_c = 25.5f,
              .gx_dps = 0.0f, .gy_dps = 0.0f, .gz_dps = 0.0f },
};

/* ---------------------------------------------------------------------------
 * 【实现】—— 签名必须和 mpu6050.h 里一模一样，否则链接器找不到
 * -------------------------------------------------------------------------*/

mpu6050_err_t mpu6050_init(void)
{
    /* 桩不判断对错，只播「当前设定」—— 遥控杆是什么，它就演什么 */
    return stub_init_err;
}

mpu6050_err_t mpu6050_read(mpu6050_data_t *out)
{
    if (stub_fail_times > 0)
    {
        stub_fail_times--;       /* 记一次账：这种错少欠一次 */
        return stub_read_err;    /* 报错时【不碰】*out —— 要和真驱动一致 */
    }

    *out = stub_data;            /* 整包播出（一行；靠 struct 整体赋值） */
    return MPU6050_OK;
}
