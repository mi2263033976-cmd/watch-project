/* ============================================================================
 * mpu6050.h —— MPU6050 器件层（Driver）对外契约
 *
 * 分层：main.c(app) → mpu6050_handler → 【本层】 → soft_i2c(时序)
 *
 * 本层对外只有两件事：① 一次性配置（init） ② 读一整包（read）
 *   · 寄存器地址 / 位域 / 默认值   → 出处 `RM-MPU-6000A.pdf`
 *   · 换算常数（灵敏度）/ 就绪时间 → 出处 `PS-MPU-6000A.pdf` §6.1~6.3
 * ==========================================================================*/
#ifndef __MPU6050_H__
#define __MPU6050_H__

#include <stdint.h>

/* ── 错误码：这一层报的是【这一次通不通】─────────────────────────────
 *   （handler 层的 `mpu6050_handler_status_t` 报的是"这段时间靠不靠得住"
 *     —— 两者不是一个东西，别混用） */
typedef enum {
    MPU6050_OK = 0,        /* 成功                                          */
    MPU6050_ERR_NACK,      /* 地址/数据没被 ACK：总线不通、器件不在、当前不响应 */
    MPU6050_ERR_ID,        /* WHO_AM_I 不是期望值：这不是 MPU6050            */
    MPU6050_ERR_BUSY,      /* 复位轮询超时：器件在位，但迟迟没就绪            */
    MPU6050_ERR_PARAM,     /* 调用方传了空指针 —— 调用的问题，不是器件的问题  */
} mpu6050_err_t;

/* ── 数据包：两层，raw 是【真身】，conv 是【派生】─────────────────────
 *
 *   raw  —— 器件寄存器的原始读数（16 位有符号整数）。
 *           ⚠️ 单独一个 raw 没有物理意义 —— 必须配上量程才翻译得出来。
 *           留着它的两个理由：① 能自查（换算对不对，回头拿 raw 复算）
 *                              ② 将来做标定 / 换量程时，它是唯一的一手数据
 *
 *   conv —— 按当前量程换算出的物理量（raw ÷ 灵敏度）：
 *           `_g` = 重力加速度 g（±2g 档）· `_dps` = °/秒（±2000°/s 档）· `_c` = 摄氏度
 *           ⚠️ 单位挂在字段名后缀上 —— 7 个 float 混在一起，编译器分不清谁是谁
 *
 *   ⚠️ conv 随时可以从 raw 重算出来；raw 丢了就找不回来 ⇒ 顺序也是 raw 在前。
 *   ⚠️ 字段顺序照手册（`0x3B` 起）：加速度 3 轴 → 温度 → 陀螺 3 轴。
 *      "温度在第 4 个"这件事，在拼装和日志里都最容易数错。
 */
typedef struct {
    int16_t ax, ay, az;    /* 加速度：X / Y / Z（原始计数） */
    int16_t temp;          /* 温度（原始计数）——★ 注意它在【中间】 */
    int16_t gx, gy, gz;    /* 角速度：X / Y / Z（原始计数） */
} mpu6050_raw_t;

typedef struct {
    float ax_g, ay_g, az_g;      /* 加速度：单位 g        */
    float temp_c;                /* 温度：单位 °C         */
    float gx_dps, gy_dps, gz_dps;/* 角速度：单位 °/s      */
} mpu6050_conv_t;

/* 一次读回的完整一包
 *   出参用 struct 而不是多个标量：7 个值是【同一时刻、同一个姿态】的完整描述，
 *   拆开单独用没有意义（只有 ax 没有 gz，那不是一个姿态）。
 *   —— 判据是"这些值是不是一个不可分的整体"，不是"值有多少个"。
 *   ⚠️ 本 struct 无 padding、无指针 ⇒ 测试里可以 memcmp 整包比；
 *      将来若加 uint8_t / bool 之类，会引入 padding，那时要改成逐字段比。 */
typedef struct {
    mpu6050_raw_t raw;
    mpu6050_conv_t conv;
} mpu6050_data_t;

/* ── 对外函数 ──────────────────────────────────────────────────────── */

/* 开机配置器件 —— ⚠️ 只调一次（内部含软复位，进主循环 = 每秒打回睡眠态） */
mpu6050_err_t mpu6050_init(void);

/* 读一次 6 轴 + 温度（一次连读 14 字节，保证同一采样时刻）
 *   ⚠️ 失败时 out 的字段【原样不动】—— 不留下"半新半旧"的包 */
mpu6050_err_t mpu6050_read(mpu6050_data_t *out);

#endif /* __MPU6050_H__ */
