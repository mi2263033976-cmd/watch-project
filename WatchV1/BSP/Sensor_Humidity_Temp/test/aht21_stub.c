/* ============================================================================
 * aht21_stub.c —— AHT21 的「测试替身」(stub)
 *
 * 作用：顶替 BSP/Sensor_Humidity_Temp/aht21.c，让 aht21_handler 能在 PC 上被测。
 *       链接时「换掉同名符号」即可，handler.c 一个字都不用改。
 *
 * 三条要求：
 *   ① 两个函数都要实现（少一个 → 链接器报 undefined symbol）
 *   ② 一行 I2C、一行 HAL 都不能有（它跟硬件无关，只跟变量打交道）
 *   ③ 测试能「指挥」它 —— 这是 stub 的灵魂
 * ==========================================================================*/

#include "aht21.h"
#include <stdint.h>

/* ---------------------------------------------------------------------------
 * 【遥控杆】—— 测试开跑前设定，stub 照着演
 *            注意：桩自己【不含任何判断逻辑】，它只负责把设定播出去
 * -------------------------------------------------------------------------*/

aht21_err_t stub_init_err   = AHT21_OK;   /* aht21_init 该返回什么            */
aht21_err_t stub_read_err   = AHT21_OK;   /* aht21_read_* 该报什么错          */
uint32_t    stub_fail_times = 0;          /* 那个错「还要再报几次」0 = 不报了  */
float       stub_temp       = 25.6f;      /* 成功时吐出的温度                  */
float       stub_humi       = 60.0f;      /* 成功时吐出的湿度                  */

/* ---------------------------------------------------------------------------
 * 【实现】—— 签名必须和 aht21.h 里一模一样，否则链接器找不到
 * -------------------------------------------------------------------------*/

aht21_err_t aht21_init(void)
{
    /* 桩不判断对错，只播「当前设定」—— 遥控杆是什么，它就演什么 */
    return stub_init_err;
}

aht21_err_t aht21_read_temp_humi(float *temp, float *humi)
{
    if (stub_fail_times > 0)
    {
        stub_fail_times--;      /* 记一次账：这种错少欠一次 */
        return stub_read_err;   /* 报错时【不碰】*temp / *humi —— 要和真驱动一致 */
    }

    *temp = stub_temp;          /* 走到这里 = 这一轮成功 */
    *humi = stub_humi;
    return AHT21_OK;
}
